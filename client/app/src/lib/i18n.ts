function initialLang(): Lang | null {
  try {
    const v = localStorage.getItem('ph:lang')
    if (v === 'en' || v === 'zh-CN') return v
  } catch {}
  return null
}

export const lang = ref<Lang>(initialLang() ?? (navigator.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'))
export const langExplicit = ref(initialLang() !== null)

export function setLang(l: Lang, explicit = true) {
  lang.value = l
  document.documentElement.lang = l
  if (explicit) {
    langExplicit.value = true
    try {
      localStorage.setItem('ph:lang', l)
    } catch {}
  }
}

export const t = computed<Dict>(() => (lang.value === 'en' ? en : zh))

/** Fills {name} placeholders; "one|many" templates pick a form by `vars.n`. */
export function fmt(s: string, vars: Record<string, string | number>): string {
  if (s.includes('|') && vars.n !== undefined) s = s.split('|')[Number(vars.n) === 1 ? 0 : 1]
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

export function relTime(ts: number, now = Date.now()): string {
  const d = Math.max(0, now - ts)
  const s = t.value
  if (d < 60_000) return s.justNow
  if (d < 3_600_000) return fmt(s.minutesAgo, { n: Math.floor(d / 60_000) })
  if (d < 86_400_000) return fmt(s.hoursAgo, { n: Math.floor(d / 3_600_000) })
  if (d < 7 * 86_400_000) return fmt(s.daysAgo, { n: Math.floor(d / 86_400_000) })
  return new Date(ts).toLocaleDateString(lang.value)
}

export function duration(ms?: number): string {
  if (!ms) return ''
  if (ms < 1000) return `${ms}ms`
  const s = Math.round(ms / 1000)
  return s < 60 ? `${s}s` : `${Math.floor(s / 60)}m${s % 60 ? ` ${s % 60}s` : ''}`
}
