import { expect, test } from '@playwright/test'
import { artifacts, chat, CONTROL, dockButton, openChat, send } from './helpers'

test.describe('chat panel', () => {
  test('streams a reply and shows the done footer', async ({ page }) => {
    const c = await openChat(page)
    await send(c, 'hello there')
    await expect(c.locator('.turn .user .text').last()).toHaveText('hello there')
    await expect(c.locator('.turn .md').last()).toContainText('Echo: hello there')
    await expect(c.locator('.turn .foot .st').last()).toHaveClass(/done/)
    await expect(c.locator('textarea')).toHaveValue('')
  })

  test('errors show a retry button that re-runs the turn', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:fail] boom')
    await expect(c.locator('.turn div.err-box').last()).toContainText('Scripted failure')
    await expect(c.locator('.turn .foot .st').last()).toHaveClass(/error/)
    await c.locator('.turn .foot button', { hasText: 'Retry' }).last().click()
    await expect(c.locator('.turn div.err-box')).toHaveCount(2)
  })

  test('thinking, tool cards and changed files render', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:think] [fake:edit] edit things')
    await expect(c.locator('.turn .foot .st').last()).toHaveClass(/done/)
    const thinking = c.locator('.turn details.thinking').last()
    await expect(thinking).not.toHaveAttribute('open')
    await thinking.locator('summary').click()
    await expect(thinking).toHaveAttribute('open')
    await expect(thinking).toContainText('Considering the request')
    const group = c.locator('.turn [data-testid="tool-group"]').last()
    await expect(group.locator('.head').first()).toContainText('Used 1 tool')
    await group.locator('.head').first().click()
    const tool = group.locator('.tool').last()
    await expect(tool).toContainText('src/App.vue')
    await tool.locator('.head').click()
    await expect(tool.locator('.body')).toContainText('ok')
    await c.locator('.turn .files-head').last().click()
    await expect(c.locator('.turn .files li').last()).toHaveText('src/App.vue')
  })

  test('messages queue behind a running turn; queued items can be withdrawn; Stop cancels', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:slow] first')
    await expect(c.locator('.indicator')).toBeVisible()
    await send(c, 'second')
    await send(c, 'third')
    await expect(c.locator('.queue .qi')).toHaveCount(2)
    await expect(c.locator('.queue .qh')).toContainText('2')
    await c.locator('.queue .qi').nth(1).locator('button[title="Withdraw"]').click()
    await expect(c.locator('.queue .qi')).toHaveCount(1)
    await c.locator('.composer button.danger').click()
    await expect(c.locator('.turn .foot .st.cancelled')).toHaveCount(1)
    await expect(c.locator('.turn .md').last()).toContainText('Echo: second')
    await expect(c.locator('.queue')).toBeHidden()
  })

  test('ask_question shows a card; the answer flows back to the agent', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:ask] pick a color')
    const card = c.locator('.ask.card')
    await expect(card.locator('.prompt')).toHaveText('Which color?')
    await expect(card.locator('.opt .rec')).toHaveCount(1)
    await card.locator('.opt', { hasText: 'Blue' }).click()
    await card.locator('button', { hasText: 'Submit' }).click()
    await expect(c.locator('.turn .md').last()).toContainText('You answered:')
    await expect(c.locator('.turn .md').last()).toContainText('Blue')
    await expect(card.locator('.sum')).toContainText('Blue')
  })

  test('ask_form validates required URL fields', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:form] need repo')
    const card = c.locator('.ask.card')
    const submit = card.locator('button', { hasText: 'Submit' })
    await expect(submit).toBeDisabled()
    await card.locator('input').fill('https://example.com/repo.git')
    await submit.click()
    await expect(c.locator('.turn .md').last()).toContainText('https://example.com/repo.git')
  })

  test('page control: off by default, then the agent clicks on the page when enabled', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:click=Save] try clicking')
    await expect(c.locator('.turn .foot .st').last()).toHaveClass(/done/)
    await expect(page.locator('#out')).toHaveText('')
    await c.locator('[data-testid="settings"]').click()
    await c.locator('[data-testid="toggle-control"]').check()
    await expect(c.locator('[data-testid="control-status"]')).toBeVisible()
    await c.locator('[data-testid="settings"]').click()
    await expect(page.locator('page-harness-root .banner')).toBeVisible()
    await page.locator('#name').fill('Ada')
    await send(c, '[fake:click=Save] click save')
    await expect(page.locator('#out')).toHaveText('saved Ada')
    await expect(c.locator('.turn [data-testid="tool-group"]').last()).toContainText('page_click')
    await c.locator('[data-testid="settings"]').click()
    await c.locator('[data-testid="toggle-control"]').uncheck()
    await expect(page.locator('page-harness-root .banner')).toBeHidden()
  })

  test('chats persist across reloads and can be switched', async ({ page }) => {
    const c = await openChat(page)
    await send(c, 'persist me')
    await expect(c.locator('.turn .md').last()).toContainText('Echo: persist me')
    await page.reload()
    const c2 = chat(page)
    await expect(c2.locator('.turn .user .text').last()).toHaveText('persist me')
    await c2.locator('[data-testid="chat-switcher"]').click()
    await c2.locator('[data-testid="new-chat"]').click()
    await expect(c2.locator('.turn')).toHaveCount(0)
  })
})

test.describe('artifacts', () => {
  test('artifact chip opens the artifacts window with a rendered markdown preview; versions are kept', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:artifact] write report')
    const chip = c.locator('.turn .chip.art').last()
    await expect(chip).toContainText('report.md')
    await chip.click()
    await expect(page.locator('page-harness-root .art-mask')).toBeVisible()
    const a = artifacts(page)
    await expect(a.locator('.tab.on .nm')).toHaveText('report.md')
    await expect(a.locator('.doc h1')).toHaveText('Report')
    await expect(a.locator('.doc table td').first()).toHaveText('1')
    await expect(a.locator('.doc pre.shiki')).toBeVisible()

    const v1 = Number(/v(\d+)/.exec((await chip.textContent()) ?? '')?.[1] ?? 1)
    await send(c, '[fake:artifact] again')
    await expect(c.locator('.turn .chip.art').last()).toContainText(`v${v1 + 1}`)
    await expect(a.locator('[data-testid="version-select"]')).toBeVisible()
    await a.locator('[data-testid="version-select"]').selectOption('1')
    await expect(a.locator('.chip.ro')).toBeVisible()

    await a.locator('[data-testid="tab-all"]').click()
    await expect(a.locator('.tile[data-artifact="report.md"]')).toBeVisible()
    await page.locator('page-harness-root .art .close').click()
    await expect(page.locator('page-harness-root .art-mask')).toBeHidden()
  })

  test('HTML artifacts render in a sandboxed frame with scripts but no access to the panel', async ({ page }) => {
    const c = await openChat(page)
    await send(c, '[fake:html] mock')
    await expect(c.locator('.turn .chip.art').last()).toContainText('mock.html')
    await dockButton(page, 'artifacts').click()
    const a = artifacts(page)
    await a.locator('.tile[data-artifact="mock.html"]').click()
    const frame = a.locator('.frame-box iframe')
    await expect(frame).toHaveAttribute('sandbox', /allow-scripts/)
    expect(await frame.getAttribute('sandbox')).not.toContain('allow-same-origin')
    await expect(a.frameLocator('.frame-box iframe').locator('#m')).toHaveText('Mockup ok')
    await a.locator('button', { hasText: 'Mobile' }).click()
    await expect(a.locator('.frame-wrap')).toBeVisible()
  })
})

test.describe('history page', () => {
  test('lists chats, searches across turns and deep-links into a turn', async ({ page, context }) => {
    const c = await openChat(page)
    await send(c, 'zebra crossing unique words')
    await expect(c.locator('.turn .md').last()).toContainText('Echo: zebra')
    const h = await context.newPage()
    await h.goto(`${CONTROL}/__ph/history`)
    await expect(h.locator('.item').first()).toBeVisible()
    await h.locator('[data-testid="history-search"]').fill('zebra')
    const hit = h.locator('.item.hit').first()
    await expect(hit).toBeVisible()
    await expect(hit.locator('mark').first()).toHaveText(/zebra/i)
    await hit.click()
    await expect(h).toHaveURL(/#chat=.+&turn=/)
    await expect(h.locator('.turn .user .text', { hasText: 'zebra crossing unique words' })).toBeVisible()
    const md = await h.request.get(`${CONTROL}/__ph/api/chats/${/chat=([^&]+)/.exec(h.url())![1]}/export.md`, { headers: { 'Sec-Fetch-Site': 'same-origin' } })
    expect(md.status()).toBe(200)
    expect(await md.text()).toContain('zebra crossing unique words')
  })

  test('history page refuses to be framed and the API rejects cross-site requests', async ({ page }) => {
    const res = await page.request.get(`${CONTROL}/__ph/history`)
    expect(res.headers()['content-security-policy']).toContain("frame-ancestors 'none'")
    const api = await page.request.post(`${CONTROL}/__ph/api/chats`, { data: {}, headers: { Origin: 'http://evil.test' } })
    expect([401, 403]).toContain(api.status())
  })
})
